const COUNTRY_NAMES_MS = {
  MY: 'Malaysia',
  ID: 'Indonesia',
  TH: 'Thailand',
  US: 'Amerika Syarikat',
  GB: 'United Kingdom',
  JP: 'Jepun',
  KR: 'Korea Selatan'
};

const COUNTRY_NAMES_EN = {
  MY: 'Malaysia',
  ID: 'Indonesia',
  TH: 'Thailand',
  US: 'United States',
  GB: 'United Kingdom',
  JP: 'Japan',
  KR: 'South Korea'
};

export function getLang() {
  const urlLang = new URLSearchParams(location.search).get('lang');
  if (urlLang && ['en', 'ms', 'bm'].includes(urlLang.toLowerCase())) {
    const l = urlLang.toLowerCase() === 'bm' ? 'ms' : urlLang.toLowerCase();
    try { localStorage.setItem('moviehub_lang', l); } catch {}
    return l;
  }
  try {
    const saved = localStorage.getItem('moviehub_lang');
    if (saved && ['en', 'ms'].includes(saved)) return saved;
  } catch {}
  return 'en';
}

export function setLang(lang) {
  const normalized = (lang === 'bm' ? 'ms' : lang);
  try {
    localStorage.setItem('moviehub_lang', normalized);
  } catch {}
  const params = new URLSearchParams(location.search);
  params.set('lang', normalized);
  location.search = params.toString();
}

export function t(key, params = {}) {
  const lang = getLang();
  let str = translations[lang]?.[key] ?? translations['en']?.[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return str;
}

export function countryDisplayName(code) {
  const lang = getLang();
  if (lang === 'ms' && COUNTRY_NAMES_MS[code]) return COUNTRY_NAMES_MS[code];
  if (lang === 'en' && COUNTRY_NAMES_EN[code]) return COUNTRY_NAMES_EN[code];
  try {
    const intl = new Intl.DisplayNames([lang === 'ms' ? 'ms' : 'en'], {type: 'region'});
    return intl.of(code) || code;
  } catch {
    return code;
  }
}
